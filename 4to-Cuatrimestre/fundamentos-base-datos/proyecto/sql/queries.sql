-- OTRAS TIPOS DE CONSULTAS
-- Vista de Productos
SELECT
	PRODUCTS.id AS "NO.",
	PRODUCTS.sku AS "SKU",
	PRODUCTS.name AS "PRODUCTO",
	PRODUCTS.salePrice AS "PRECIO DE VENTA",
	PRODUCTS.stock AS "EXISTENCIAS",
	CATEGORIES.category AS "CATEGORÍA"
